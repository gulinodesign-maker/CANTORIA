const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8'),js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(js);new vm.Script(js);
const release=require('../release.json');assert.deepEqual(release,{version:'1.1',build:43});
assert.ok(js.includes("const releaseInfo={version:'1.1',build:null}"));
const a=js.indexOf('function headerHTML()'),b=js.indexOf('function navHTML()',a);
assert.ok(a>=0&&b>a);
const ctx={releaseInfo:{version:release.version,build:release.build},escape:s=>String(s),state:{view:'settings'},CATHOLIC_CORNER:'<svg></svg>'};
vm.runInNewContext(js.slice(a,b)+'this.showHeader=headerHTML;',ctx);
assert.ok(ctx.showHeader().includes('Versione 1.1 (43)'));
ctx.releaseInfo.build=44;
assert.ok(ctx.showHeader().includes('Versione 1.1 (44)'),'Next build must update automatically');
assert.ok(js.includes("fetch('./release.json',{cache:'no-store'})"));
assert.ok(js.includes("if(state.view==='settings'&&!state.songId)render()"));
assert.ok(fs.readFileSync('scripts/prepare-ios.sh','utf8').includes('cp index.html release.json audio-follow.js'));
assert.ok(fs.readFileSync('sw.js','utf8').includes("'./release.json'"));
console.log('Dynamic Settings build read from release.json, bundled for offline iOS');
