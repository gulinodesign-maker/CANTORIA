const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(js);new vm.Script(js);
assert.deepEqual(require('../release.json'),{version:'1.1',build:48});
const head=js.slice(js.indexOf('function headerHTML(){'),js.indexOf('function navHTML(){'));
const detail=js.slice(js.indexOf('function massDetailHTML(){'),js.indexOf('const OCR_JS_URL='));
assert.ok(!head.includes('class="mass-topbar-overline"'),'Remove visible SCALETTA overline');
assert.ok(!head.includes('class="mass-topbar-count"'),'Remove visible 10 canti or count');
assert.ok(!detail.includes('Tieni premuto un canto e trascinalo'),'Remove visible drag help');
assert.ok(!detail.includes('class="mass-reorder-help"'),'Remove unused help paragraph');
assert.ok(detail.includes('data-mass-reorder='),'Long-press reordering must still be enabled');
assert.ok(detail.includes('data-reorder-item='),'Every Mass song retains sortable identifier');
assert.ok(head.includes('mass-topbar-name')&&head.includes('mass-topbar-date'),'Mass title/date must remain');
assert.ok(head.includes("backCornerHTML('back-masses')"),'Corner Back remains');
const nameIndex=head.indexOf('<strong class="mass-topbar-name">');
assert.ok(nameIndex>=0);
const ctx={state:{view:'masses',massId:'m1'},currentMass(){return {name:'Messa 1',date:'2026-11-22',items:Array.from({length:10},(_,i)=>({id:'i'+i}))}},massDateDisplay(){return '22/11/2026'},escape:x=>x,backCornerHTML:()=>'<button data-action="back-masses"></button>'};
vm.runInNewContext(head+'this.getHeader=headerHTML;',ctx);
const rendered=ctx.getHeader();
assert.ok(rendered.includes('Messa 1')&&rendered.includes('22/11/2026'));
assert.ok(!rendered.includes('SCALETTA')&&!rendered.includes('10 canti'));
const marker='/* CANTORIA 1.1 (47): genuinely LEFT portrait playback controls and clean Mass header.';
const start=html.indexOf(marker);assert.ok(start>=0);
const css=html.slice(start,html.indexOf('</style>',start));
assert.match(css,/@media screen and \(orientation:portrait\)\{[\s\S]*?\.reader-layer\.reader-portrait \.reader-toolbar-left\{[^}]*left:clamp\(38px,6vw,56px\)!important;/);
assert.ok(css.includes('left:38px!important;right:auto!important'),'Small portrait screens keep controls left');
assert.ok(!css.includes('right:114px!important'),'No old right-aligned transport rule');
console.log('PASS: Mass header name/date only, no visible reordering help, portrait controls truly left');
